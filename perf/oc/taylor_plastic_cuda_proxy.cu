// Persistent-kernel proxy for the taylor_plastic native explicit run (oc-opt Phase G0).
//
// Question: can a CUDA port of the taylor_plastic time loop (780 nodes, 540
// JC hex8 bricks, 123 steps of under-integrated H8 + velocity-Verlet +
// penalty anvil) beat the 0.086 s native CPU run, and at what distance from
// roofline?
//
// Design: ONE persistent kernel holds the whole time loop on-device (no
// per-step launch/transfer). Inside, the proxy mirrors the real port a
// Phase G1 would write:
//   * exact taylor mesh topology (780 nodes, 540 bricks, deck masses),
//   * greedy 9-color element ordering (race-free scatter, __syncthreads
//     between colors),
//   * per element: current-config centroid Jacobian + gradients, uniform
//     strain increment, bulk viscosity (quadratic only, c1 = 0 like the
//     native plastic arm), Johnson-Cook rated radial return (80-iteration
//     bisection), V B^T (sigma - q I) scatter, Flanagan-Belytschko
//     viscous hourglass, erosion at ep >= 0.18,
//   * rising penalty anvil (227 m/s, k = 0.5 E Le) with the overdamped
//     dashpot, velocity-Verlet kick-drift-kick at fixed dt,
//   * fixed dt = stop/123 (the native rides its dt_max cap: 123 steps).
// Fidelity: final DZ/PLAS plus the FNZ second-half plateau mean must match
// the native run before timing is trusted; the report records it.
//
// Known deviations (all documented in the report): fixed dt (native adapts
// around the same mean), no TH sampling, no energy-drift bookkeeping,
// coloring differs (greedy vs serial order) but the math is order-free.
// Erosion is exact (same ep rule, forces zeroed, states kept for probes).
//
// Build: nvcc -O2 -arch=native -o taylor_proxy taylor_plastic_cuda_proxy.cu
// Run:   ./taylor_proxy [nstep]     (default 123, the sonium count)

