//! Permissive seed pack: typical handbook values, fully cited, **no
//! manufacturer datasheet data**.
//!
//! Every entry is [`ProvenanceClass::Curated`] with a public citation and a
//! permissive licence note. Values are *typical* starting points for
//! simulation, not production datasheets — re-measure for a real product.

use crate::curves::{BhCurveData, BhPoint, ComplexModulusCurve, ComplexModulusPoint};
use crate::material::{
    Acoustic, Electric, Elastic, JcaParams, Magnetic, Material, Provenance, ProvenanceClass,
    Thermal,
};
use crate::{MaterialError, MaterialPack, Quantity};

const LIC: &str = "Permissive: typical handbook values compiled from public references; no manufacturer datasheet data. Verify before production use.";

fn q(value: f64, unit: &str, rel: f64) -> Quantity {
    Quantity::new(value, unit).with_rel_tol(rel)
}
fn prov(source: &str, citation: &str, grade: &str, method: &str) -> Provenance {
    Provenance {
        class: ProvenanceClass::Curated,
        source: source.into(),
        citation: citation.into(),
        grade: Some(grade.into()),
        reference_temperature_k: Some(293.15),
        method: Some(method.into()),
        license: LIC.into(),
    }
}
fn iso(e: f64, nu: f64, eta: Option<f64>, curve: Option<ComplexModulusCurve>) -> Option<Elastic> {
    Some(Elastic::Isotropic {
        youngs_modulus: q(e, "Pa", 0.10),
        poisson_ratio: nu,
        loss_factor: eta,
        complex_modulus: curve,
    })
}
fn curve(pts: &[(f64, f64, f64, f64)]) -> ComplexModulusCurve {
    ComplexModulusCurve {
        points: pts
            .iter()
            .map(|&(f, t, s, l)| ComplexModulusPoint {
                frequency_hz: f,
                temperature_k: t,
                storage_pa: s,
                loss_pa: l,
            })
            .collect(),
    }
}
fn bh(pts: &[(f64, f64)]) -> BhCurveData {
    BhCurveData {
        points: pts
            .iter()
            .map(|&(b, h)| BhPoint { b_t: b, h_a_per_m: h })
            .collect(),
    }
}

